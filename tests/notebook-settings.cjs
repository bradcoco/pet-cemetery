const assert=require('node:assert/strict')
exports.local=async function({store,storage,notebooks,id,noteInput}){
  const keys=['xingyu.notebookSettings.v1','xingyu.memorials.v1','xingyu.notes.v1'],saved=keys.map(key=>structuredClone(storage.get(key)))
  try{
    const original=await store.getMemorial(id)
    assert.deepEqual((await store.getNotebook(id)).tags,[])
    await store.addNotebookTag(id,' 日常 ')
    const tags=await store.addNotebookTag(id,'打疫苗'),daily=tags[0],vaccine=tags[1]
    assert.equal(daily.name,'日常');assert.equal(tags.length,2)
    for(const name of ['',null,'字'.repeat(21),'日常'])await assert.rejects(store.addNotebookTag(id,name))
    const record=await store.saveNote(id,{...noteInput,title:'周末散步',content:'今天去公园',tagIds:[daily.id,vaccine.id]})
    const all=await store.listNotes(id),selected=all.find(n=>n.id===record)
    assert.deepEqual(selected.tagIds,[daily.id,vaccine.id])
    assert.equal(notebooks.filterNotebookNotes(all,tags,'公园',daily.id).length,1)
    assert.equal(notebooks.filterNotebookNotes(all,tags,'打疫苗').length,1)
    assert.equal(notebooks.filterNotebookNotes(all,tags,'不存在',daily.id).length,0)
    assert.equal(notebooks.filterNotebookNotes(all,tags,'',vaccine.id).length,1)
    await store.saveNote(id,{...noteInput,title:'旧客户端编辑'},record)
    assert.deepEqual((await store.listNotes(id)).find(n=>n.id===record).tagIds,[daily.id,vaccine.id])
    await assert.rejects(store.saveNote(id,{...noteInput,tagIds:[daily.id,daily.id]}))
    await assert.rejects(store.saveNote(id,{...noteInput,tagIds:['foreign-tag']}),/标签/)
    await assert.rejects(store.saveNote('__overview__',{...noteInput,tagIds:[daily.id]}),/标签/)
    await store.deleteNotebookTag(id,daily.id)
    const after=await store.listNotes(id);assert.ok(after.find(n=>n.id===record));assert.deepEqual(after.find(n=>n.id===record).tagIds,[vaccine.id])
    await assert.rejects(store.saveNote(id,{...noteInput,tagIds:[daily.id]},record),/已被删除/)
    const recreated=await store.addNotebookTag(id,'日常');assert.notEqual(recreated[1].id,daily.id)
    assert.deepEqual((await store.listNotes(id)).find(n=>n.id===record).tagIds,[vaccine.id])
    await store.setNotebookPrivacy(id,'public');assert.equal((await store.getNotebook(id)).privacy,'public')
    const updated=await store.getMemorial(id)
    for(const key of ['no','story','privacy','photos','flowers','gifts'])assert.deepEqual(updated[key],original[key])
    storage.set('xingyu.memorials.v1',storage.get('xingyu.memorials.v1').map(p=>p.id===id?{...p,owner:false}:p))
    assert.equal((await store.getNotebook(id)).canWrite,false)
    for(const op of [()=>store.addNotebookTag(id,'访客'),()=>store.deleteNotebookTag(id,vaccine.id),()=>store.setNotebookPrivacy(id,'private')])await assert.rejects(op,/主人/)
    storage.set('xingyu.memorials.v1',storage.get('xingyu.memorials.v1').map(p=>p.id===id?{...p,owner:true}:p))
    await store.setNotebookPrivacy(id,'private');await assert.rejects(store.setNotebookPrivacy(id,'bad'))
    await store.setNotebookPrivacy('__overview__','public');assert.equal((await store.getNotebook('__overview__')).privacy,'public')
    assert.deepEqual((await store.getNotebook('__overview__')).tags,[])
    await store.setNotebookPrivacy('__overview__','private')
    for(let i=recreated.length;i<30;i++)await store.addNotebookTag(id,'分类'+i)
    await assert.rejects(store.addNotebookTag(id,'第31个'),/30/)
    const many=(await store.getNotebook(id)).tags.map(t=>t.id)
    await assert.rejects(store.saveNote(id,{...noteInput,tagIds:many.slice(0,11)}),/10/)
    assert.ok(await store.saveNote(id,{...noteInput,tagIds:many.slice(0,10)}))
  }finally{keys.forEach((key,i)=>saved[i]===undefined?storage.delete(key):storage.set(key,saved[i]))}
}
exports.cloud=async function({call,table,clone,id}){
  const original=clone(table('memorials').get(id)),info=(await call('owner-a',{action:'notebook',memorialId:id})).data,bookId=info.bookId,oldShare=clone(table('notebookShares').get(bookId)),originalNotes=clone([...table('notes').values()].filter(n=>n.memorialId===id&&n._openid==='owner-a'))
  const overview=(await call('owner-a',{action:'notebook',memorialId:'__overview__'})).data,oldOverview=clone(table('notebookShares').get(overview.bookId)),input={title:'接种疫苗',content:'留院观察一切正常',date:'2025-01-01',photos:[]}
  const ok=async(user,event)=>{const result=await call(user,event);assert.equal(result.ok,true,result.error);return result.data}
  try{
    await ok('owner-a',{action:'notebookTagAdd',memorialId:id,name:'日常'})
    const tags=await ok('owner-a',{action:'notebookTagAdd',memorialId:id,name:'打疫苗'}),daily=tags[0],vaccine=tags[1]
    for(const name of ['',null,'字'.repeat(21),' 日常 '])assert.equal((await call('owner-a',{action:'notebookTagAdd',memorialId:id,name})).ok,false)
    const duplicates=await Promise.all(Array.from({length:4},()=>call('owner-a',{action:'notebookTagAdd',memorialId:id,name:'绝育'})))
    assert.equal(duplicates.filter(r=>r.ok).length,1)
    const tagged=await ok('owner-a',{action:'noteSave',memorialId:id,input:{...input,tagIds:[daily.id,vaccine.id]}})
    await ok('owner-a',{action:'noteSave',memorialId:id,id:tagged,input})
    assert.deepEqual(table('notes').get(tagged).tagIds,[daily.id,vaccine.id])
    for(const tagIds of [null,{},[daily.id,daily.id],Array(11).fill(daily.id),['bad/tag'],['not-this-book']])assert.equal((await call('owner-a',{action:'noteSave',memorialId:id,input:{...input,tagIds}})).ok,false)
    assert.equal((await call('owner-a',{action:'noteSave',memorialId:'__overview__',input:{...input,tagIds:[daily.id]}})).ok,false)
    const invited=await ok('owner-a',{action:'notebookInvite',memorialId:id});assert.equal(table('notebookShares').get(bookId).tags.length,3)
    await ok('owner-b',{action:'notebookJoin',code:invited.code})
    const member=await ok('owner-b',{action:'notebook',bookId});assert.equal(member.tags.length,3)
    const friend=await ok('owner-b',{action:'noteSave',bookId,input:{...input,tagIds:[vaccine.id]}});assert.ok(friend)
    for(const user of ['owner-b','owner-c'])for(const event of [{action:'notebookTagAdd',name:'越权'},{action:'notebookTagDelete',tagId:vaccine.id},{action:'notebookPrivacy',privacy:'public'}])assert.equal((await call(user,{...event,bookId})).ok,false)
    await Promise.all([ok('owner-a',{action:'notebookTagAdd',memorialId:id,name:'体检'}),ok('owner-a',{action:'notebookPrivacy',memorialId:id,privacy:'public'})])
    const guest=await ok('owner-c',{action:'notebook',memorialId:id});assert.equal(guest.canWrite,false);assert.equal(guest.tags.length,4);assert.equal(guest.pet.story,undefined)
    assert.equal((await call('owner-c',{action:'noteSave',bookId,input:{...input,tagIds:[vaccine.id]}})).ok,false)
    assert.equal(table('notebookShares').get(bookId).inviteCode,invited.code);assert.deepEqual(table('notebookShares').get(bookId).memberIds,['owner-b'])
    for(const key of ['no','privacy','photos','story','flowers','gifts'])assert.deepEqual(table('memorials').get(id)[key],original[key])
    await ok('owner-a',{action:'notebookTagDelete',memorialId:id,tagId:vaccine.id})
    const notes=await ok('owner-b',{action:'notes',bookId})
    assert.deepEqual(notes.find(n=>n.id===tagged).tagIds,[daily.id]);assert.deepEqual(notes.find(n=>n.id===friend).tagIds,[])
    assert.equal((await call('owner-b',{action:'noteSave',bookId,id:friend,input:{...input,tagIds:[vaccine.id]}})).ok,false)
    await ok('owner-b',{action:'noteSave',bookId,id:friend,input})
    assert.deepEqual(table('notes').get(friend).tagIds,[])
    const rebuilt=await ok('owner-a',{action:'notebookTagAdd',memorialId:id,name:'打疫苗'});assert.notEqual(rebuilt.find(t=>t.name==='打疫苗').id,vaccine.id)
    await ok('owner-a',{action:'notebookPrivacy',memorialId:id,privacy:'private'})
    assert.equal((await call('owner-c',{action:'notes',bookId})).ok,false);assert.ok((await call('owner-b',{action:'notes',bookId})).ok)
    await ok('owner-a',{action:'notebookPrivacy',memorialId:'__overview__',privacy:'public'})
    const group=await ok('owner-c',{action:'notebook',bookId:overview.bookId});assert.equal(group.privacy,'public');assert.equal(group.canWrite,false)
    assert.ok((await call('owner-c',{action:'notes',bookId:overview.bookId})).ok)
    assert.equal((await call('owner-c',{action:'noteSave',bookId:overview.bookId,input})).ok,false)
    await ok('owner-a',{action:'notebookInvite',memorialId:'__overview__'});assert.equal(table('notebookShares').get(overview.bookId).notebookPrivacy,'public')
    await ok('owner-a',{action:'notebookPrivacy',memorialId:'__overview__',privacy:'private'});assert.equal((await call('owner-c',{action:'notes',bookId:overview.bookId})).ok,false)
    assert.equal((await call('owner-a',{action:'notebookPrivacy',memorialId:id,privacy:'bad'})).ok,false)
    for(let i=rebuilt.length;i<30;i++)await ok('owner-a',{action:'notebookTagAdd',memorialId:id,name:'分类'+i})
    assert.equal((await call('owner-a',{action:'notebookTagAdd',memorialId:id,name:'第31个'})).ok,false)
    const tagIds=table('notebookShares').get(bookId).tags.slice(0,10).map(t=>t.id)
    assert.ok(await ok('owner-a',{action:'noteSave',memorialId:id,input:{...input,tagIds}}))
  }finally{
    table('memorials').set(id,original)
    for(const [key,value] of [[bookId,oldShare],[overview.bookId,oldOverview]]){if(value)table('notebookShares').set(key,value);else table('notebookShares').delete(key)}
    for(const [key,note] of table('notes'))if(note.memorialId===id&&note._openid==='owner-a')table('notes').delete(key)
    for(const note of originalNotes)table('notes').set(note._id,note)
  }
  console.log('✓ 云端笔记设置：主人管理公开性与标签，共写成员仅选用，访客只读；并发增删不覆盖成员或邀请码，删除分类保留记录，总览公开可撤回')
}
